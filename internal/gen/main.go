// Command gen turns the vendored GitVerse OpenAPI 2.0 description into Go
// types.
//
// Only the "definitions" section is generated: endpoint methods are written by
// hand, because gv wraps a deliberately small slice of the 130 operations and
// hand-written signatures read better than generated ones.
//
//	go run ./internal/gen -spec spec/openapi-1.8.json -out internal/api/types_gen.go
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

type schema struct {
	Type                 string             `json:"type"`
	Description          string             `json:"description"`
	Properties           map[string]*schema `json:"properties"`
	Items                *schema            `json:"items"`
	Ref                  string             `json:"$ref"`
	AllOf                []*schema          `json:"allOf"`
	Enum                 []any              `json:"enum"`
	AdditionalProperties *schema            `json:"additionalProperties"`
	Required             []string           `json:"required"`
}

type spec struct {
	Info struct {
		Version string `json:"version"`
	} `json:"info"`
	Definitions map[string]*schema `json:"definitions"`
}

func main() {
	specPath := flag.String("spec", "spec/openapi-1.8.json", "path to the OpenAPI 2.0 description")
	outPath := flag.String("out", "internal/api/types_gen.go", "path of the generated file")
	pkgName := flag.String("pkg", "api", "package name for the generated file")
	flag.Parse()

	data, err := os.ReadFile(*specPath)
	if err != nil {
		fail(err)
	}
	var s spec
	if err := json.Unmarshal(data, &s); err != nil {
		fail(fmt.Errorf("parsing %s: %w", *specPath, err))
	}

	g := &generator{spec: &s, goNames: map[string]string{}}
	g.assignNames()
	g.buildRefGraph()

	src, err := g.render(*pkgName, *specPath)
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(*outPath, src, 0o644); err != nil {
		fail(err)
	}
	fmt.Fprintf(os.Stderr, "wrote %s (%d types from API %s)\n", *outPath, len(s.Definitions), s.Info.Version)
}

func fail(err error) {
	fmt.Fprintf(os.Stderr, "gen: %v\n", err)
	os.Exit(1)
}

type generator struct {
	spec    *spec
	goNames map[string]string // definition name -> Go type name
	refs    map[string]map[string]bool
}

// assignNames maps "response.PullRequest" to PullRequest and
// "request.CreateRepo" to CreateRepoRequest, resolving collisions by suffixing
// the original namespace.
func (g *generator) assignNames() {
	taken := map[string]string{}
	names := make([]string, 0, len(g.spec.Definitions))
	for name := range g.spec.Definitions {
		names = append(names, name)
	}
	sort.Strings(names)

	for _, name := range names {
		namespace, base, hasNS := strings.Cut(name, ".")
		if !hasNS {
			namespace, base = "", name
		}
		goName := exportedName(base)
		if namespace == "request" && !strings.HasSuffix(goName, "Request") {
			goName += "Request"
		}
		if prev, clash := taken[goName]; clash && prev != name {
			goName = exportedName(namespace) + goName
		}
		taken[goName] = name
		g.goNames[name] = goName
	}
}

// buildRefGraph records which definitions each definition points at, so that
// render can use pointers exactly where a value type would be recursive.
func (g *generator) buildRefGraph() {
	g.refs = map[string]map[string]bool{}
	for name, def := range g.spec.Definitions {
		targets := map[string]bool{}
		collectRefs(def, targets)
		g.refs[name] = targets
	}
}

func collectRefs(s *schema, out map[string]bool) {
	if s == nil {
		return
	}
	if ref := refTarget(s); ref != "" {
		out[ref] = true
	}
	for _, p := range s.Properties {
		collectRefs(p, out)
	}
	collectRefs(s.Items, out)
	collectRefs(s.AdditionalProperties, out)
	for _, a := range s.AllOf {
		collectRefs(a, out)
	}
}

// reaches reports whether target can get back to source through refs.
func (g *generator) reaches(target, source string) bool {
	seen := map[string]bool{}
	var walk func(string) bool
	walk = func(n string) bool {
		if n == source {
			return true
		}
		if seen[n] {
			return false
		}
		seen[n] = true
		for next := range g.refs[n] {
			if walk(next) {
				return true
			}
		}
		return false
	}
	return walk(target)
}

func (g *generator) render(pkgName, specPath string) ([]byte, error) {
	var b bytes.Buffer

	fmt.Fprintf(&b, "// Code generated by internal/gen; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// Source: %s (GitVerse public API %s)\n", specPath, g.spec.Info.Version)
	fmt.Fprintf(&b, "// Regenerate with: make generate\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkgName)

	names := make([]string, 0, len(g.spec.Definitions))
	for name := range g.spec.Definitions {
		names = append(names, name)
	}
	sort.Slice(names, func(i, j int) bool { return g.goNames[names[i]] < g.goNames[names[j]] })

	for _, name := range names {
		def := g.spec.Definitions[name]
		goName := g.goNames[name]
		isRequest := strings.HasPrefix(name, "request.")

		if def.Description != "" {
			fmt.Fprintf(&b, "// %s %s\n", goName, oneLine(def.Description))
		} else {
			fmt.Fprintf(&b, "// %s maps the %q schema.\n", goName, name)
		}

		if def.Type != "object" && len(def.Properties) == 0 {
			fmt.Fprintf(&b, "type %s %s\n\n", goName, g.goType(name, def, isRequest, false))
			continue
		}

		fmt.Fprintf(&b, "type %s struct {\n", goName)
		props := make([]string, 0, len(def.Properties))
		for p := range def.Properties {
			props = append(props, p)
		}
		sort.Strings(props)

		required := map[string]bool{}
		for _, r := range def.Required {
			required[r] = true
		}

		usedFields := map[string]bool{}
		for _, p := range props {
			field := def.Properties[p]
			fieldName := exportedName(p)
			for usedFields[fieldName] {
				fieldName += "_"
			}
			usedFields[fieldName] = true
			// Requests use pointers for scalars so that an unset field is
			// omitted rather than sent as a zero value: PATCH endpoints treat
			// an empty string as "clear this".
			typeName := g.goType(name, field, isRequest && !required[p], false)
			tag := p
			if !required[p] {
				tag += ",omitempty"
			}
			if field.Description != "" {
				fmt.Fprintf(&b, "\t// %s\n", oneLine(field.Description))
			}
			if len(field.Enum) > 0 {
				fmt.Fprintf(&b, "\t// Values: %s\n", enumList(field.Enum))
			}
			fmt.Fprintf(&b, "\t%s %s `json:\"%s\"`\n", fieldName, typeName, tag)
		}
		fmt.Fprintf(&b, "}\n\n")
	}

	src, err := format.Source(b.Bytes())
	if err != nil {
		// Emit the unformatted source alongside the error to make debugging
		// the generator possible.
		os.WriteFile("/tmp/gv-gen-broken.go", b.Bytes(), 0o644)
		return nil, fmt.Errorf("formatting generated source: %w", err)
	}
	return src, nil
}

// goType renders the Go type for a schema. owner is the definition currently
// being generated, used for the recursion check. wantPtr requests a pointer for
// scalar types.
func (g *generator) goType(owner string, s *schema, wantPtr bool, inCollection bool) string {
	if s == nil {
		return "any"
	}

	if ref := refTarget(s); ref != "" {
		goName, ok := g.goNames[ref]
		if !ok {
			return "any"
		}
		// A value type would be infinitely sized if the target can lead back
		// here; inside slices and maps that is not a problem.
		if !inCollection && g.reaches(ref, owner) {
			return "*" + goName
		}
		return goName
	}

	switch s.Type {
	case "string":
		return maybePtr("string", wantPtr)
	case "boolean":
		return maybePtr("bool", wantPtr)
	case "integer":
		return maybePtr("int64", wantPtr)
	case "number":
		return maybePtr("float64", wantPtr)
	case "array":
		return "[]" + g.goType(owner, s.Items, false, true)
	case "object":
		if s.AdditionalProperties != nil {
			return "map[string]" + g.goType(owner, s.AdditionalProperties, false, true)
		}
		if len(s.Properties) == 0 {
			return "map[string]any"
		}
		// Inline object literals do not occur in the current specification;
		// fall back to a generic map rather than inventing a type name.
		return "map[string]any"
	default:
		return "any"
	}
}

func maybePtr(t string, ptr bool) string {
	if ptr {
		return "*" + t
	}
	return t
}

func refTarget(s *schema) string {
	if s == nil {
		return ""
	}
	if s.Ref != "" {
		return strings.TrimPrefix(s.Ref, "#/definitions/")
	}
	// The specification uses allOf only to attach a description to a $ref.
	for _, a := range s.AllOf {
		if t := refTarget(a); t != "" {
			return t
		}
	}
	return ""
}

// initialisms are rendered in full caps, per Go naming conventions.
var initialisms = map[string]string{
	"id": "ID", "ids": "IDs", "url": "URL", "urls": "URLs", "uri": "URI",
	"api": "API", "html": "HTML", "http": "HTTP", "https": "HTTPS",
	"json": "JSON", "sha": "SHA", "ssh": "SSH", "gpg": "GPG", "ip": "IP",
	"dto": "DTO", "sso": "SSO", "ui": "UI", "cpu": "CPU", "os": "OS",
	"ci": "CI", "cd": "CD", "vcs": "VCS", "smtp": "SMTP", "tls": "TLS",
}

// exportedName converts snake_case, kebab-case or PascalCase input into an
// exported Go identifier.
func exportedName(s string) string {
	// Reaction keys are literally "+1" and "-1"; spell the sign out so the two
	// do not collapse onto the same identifier.
	switch {
	case strings.HasPrefix(s, "+"):
		s = "plus_" + s[1:]
	case strings.HasPrefix(s, "-"):
		s = "minus_" + s[1:]
	}

	parts := strings.FieldsFunc(s, func(r rune) bool {
		return !((r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9'))
	})
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		if up, ok := initialisms[strings.ToLower(p)]; ok {
			b.WriteString(up)
			continue
		}
		// Keep existing capitalisation for already-camelCase segments.
		runes := []rune(p)
		b.WriteString(strings.ToUpper(string(runes[0])))
		b.WriteString(string(runes[1:]))
	}
	name := b.String()
	if name == "" {
		return "Field"
	}
	if r := []rune(name)[0]; r >= '0' && r <= '9' {
		return "F" + name
	}
	return name
}

func oneLine(s string) string {
	s = strings.ReplaceAll(s, "\r\n", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	return strings.TrimSpace(s)
}

func enumList(values []any) string {
	parts := make([]string, 0, len(values))
	for _, v := range values {
		parts = append(parts, fmt.Sprintf("%v", v))
	}
	return strings.Join(parts, ", ")
}
